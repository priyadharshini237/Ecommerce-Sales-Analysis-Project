use ecommerce_analysis;
drop table if exists customers;
create table customers
(
   Customer_ID varchar(50),
   Customers_name varchar(100),
   Gender varchar(20),
   Age int,
   Date_of_Birth int,
   Email varchar(100),
   Phone varchar(20),
   City varchar(100),
   State varchar(100),
   Country varchar(100),
   Pincode int,
   Registration_Date int,
   Membership_label varchar(20),
   Loyalty_Points varchar(100),
   Preferred_Device varchar(50)
);

 



 







   
 